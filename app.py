import streamlit as st
import joblib
import os

# --------------------------------------------------
# Page configuration
# --------------------------------------------------

st.set_page_config(
    page_title="AI News Classification",
    page_icon="📰",
    layout="centered"
)

# --------------------------------------------------
# Application title
# --------------------------------------------------

st.title("📰 AI-Powered News Classification")
st.write(
    "Enter a news headline or article below. "
    "The machine learning model will predict its category."
)

st.divider()

# --------------------------------------------------
# Load trained model files
# --------------------------------------------------

MODEL_PATH = "models/news_classifier.pkl"
VECTORIZER_PATH = "models/tfidf_vectorizer.pkl"
CATEGORIES_PATH = "models/news_categories.pkl"


@st.cache_resource
def load_artifacts():
    model = joblib.load(MODEL_PATH)
    vectorizer = joblib.load(VECTORIZER_PATH)
    categories = joblib.load(CATEGORIES_PATH)

    return model, vectorizer, categories


try:
    model, vectorizer, categories = load_artifacts()
    st.success("Classification model loaded successfully.")

except Exception as e:
    st.error(
        "The model could not be loaded. "
        "Please check that all three model files "
        "are present inside the models folder."
    )
    st.stop()

# --------------------------------------------------
# User input
# --------------------------------------------------

news_text = st.text_area(
    "Enter news text",
    placeholder=(
        "Example: The government announced new economic "
        "measures to support business growth..."
    ),
    height=180
)

# --------------------------------------------------
# Classification
# --------------------------------------------------

if st.button("Classify News", type="primary"):

    if not news_text.strip():
        st.warning("Please enter a news headline or article.")

    else:
        with st.spinner("Classifying news..."):

            features = vectorizer.transform([news_text])
            prediction = model.predict(features)[0]

        st.subheader("Classification Result")

        st.success(f"Predicted Category: {prediction}")

        st.caption(
            "This prediction is generated by the trained "
            "machine learning model. Results may be incorrect "
            "for text unlike the training data."
        )

# --------------------------------------------------
# Project information
# --------------------------------------------------

with st.expander("About this project"):

    st.write(
        """
        This application demonstrates supervised text
        classification using Natural Language Processing.

        **Technologies**
        - Python
        - TF-IDF Vectorization
        - Scikit-learn
        - Streamlit

        The model predicts categories learned from the
        training dataset.
        """
    )

st.divider()

st.caption("News Classification | Machine Learning Assignment 2")
